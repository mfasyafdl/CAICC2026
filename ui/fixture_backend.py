"""Preview backend (fictional data only) for the VisitPrep UI.

Owned by Person 2. This is a *preview-only* stand-in used when the environment
variable ``VISITPREP_PREVIEW=1`` is set, so the interface can be demoed before
Person 1 implements the real core modules. It contains **no business logic**:

- ``extract_record`` returns one of the clearly-labeled fictional records from
  ``core/fixtures.py`` verbatim (it never parses the patient's free text).
- ``choose_follow_up_question`` returns fixed, clearly-fictional placeholder
  questions.
- ``merge_answer`` returns the record unchanged.
- ``check_alerts`` returns nothing (no alert rules are re-implemented; the UI
  shows "Alerts unavailable in preview").
- ``generate_summary`` returns fixed, clearly-fictional placeholder text (no
  summary composition).

Fixture code is only ever reached when ``VISITPREP_PREVIEW=1``; the preview
banner is shown on every step so the fictional data is never presented
unlabeled.
"""

from __future__ import annotations

import copy

from core.fixtures import FIXTURE_FEVER_ADULT
from core.schema import SummaryOutput

__all__ = [
    "check_alerts",
    "choose_follow_up_question",
    "extract_record",
    "generate_summary",
    "merge_answer",
]

_PREVIEW_QUESTIONS: tuple[str, ...] = (
    "Preview: How long have you had this symptom?",
    "Preview: Are you taking any medicines?",
    "Preview: Do you have any allergies?",
    "Preview: Have you seen anyone about this before?",
    "Preview: What worries you most about this symptom?",
)


def extract_record(symptom_text, patient_details=None):
    """Return a fictional fixture record; the free text is never parsed."""
    del symptom_text, patient_details
    return copy.deepcopy(FIXTURE_FEVER_ADULT)


def choose_follow_up_question(record, asked, max_questions=5):
    """Return the next fixed fictional question, or ``None`` when done."""
    del record
    count = len(asked or [])
    if count >= min(max_questions, len(_PREVIEW_QUESTIONS)):
        return None
    return _PREVIEW_QUESTIONS[count]


def merge_answer(record, question, answer):
    """Return ``record`` unchanged (no answer merging in preview)."""
    del question, answer
    return copy.deepcopy(record)


def check_alerts(record):
    """Return no alerts (alert rules live in core, not here)."""
    del record
    return []


def generate_summary(record, asked):
    """Return fixed, clearly-fictional placeholder summary text."""
    del record, asked
    return SummaryOutput(
        doctor_card=(
            "Preview: this is placeholder text shown with fictional data. The "
            "doctor card will appear here once the core summary module is "
            "implemented."
        ),
        patient_script=(
            "Preview: fictional patient-script placeholder. The real script "
            "will be generated by core once it is implemented."
        ),
        priority_questions=[
            "Preview: a fictional example question.",
            "Preview: another fictional example question.",
            "Preview: a third fictional example question.",
        ],
    )